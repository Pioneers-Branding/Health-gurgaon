/** How an event was verified, in Hindi where the wording follows a known pattern
 * ("Called organiser (RWA secretary) on 14 Oct 2026", "Resident submission · not yet confirmed"). */
export function sourceText(lang: Lang, source: string): string {
  if (lang !== "hi") return source;
  const called = source.match(/^Called (?:the )?(.+?) on (\d{1,2} \w{3} \d{4})$/);
  if (called) {
    const who = called[1]
      .replace(/^organiser \((.+)\)$/, "आयोजक ($1)")
      .replace(/^organiser$/, "आयोजक")
      .replace(/RWA secretary/, "RWA सचिव")
      .replace(/^support group’s coordinator$/, "सहायता समूह के समन्वयक");
    const [d, mon, y] = called[2].split(" ");
    const month = hi.months[["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"].indexOf(mon)] ?? mon;
    return `${d} ${month} ${y} को ${who} को कॉल किया`;
  }
  const submission = source.match(/^(Resident|NGO|Society|Organiser) submission · (not yet confirmed|changes requested)$/);
  if (submission) {
    const who = { Resident: "निवासी", NGO: "एनजीओ", Society: "सोसाइटी", Organiser: "आयोजक" }[submission[1] as "Resident"];
    return `${who} ने भेजा · ${submission[2] === "not yet confirmed" ? "अभी पुष्टि नहीं हुई" : "बदलाव माँगे गए"}`;
  }
  return source;
}
