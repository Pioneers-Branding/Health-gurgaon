/** "14 facilities", "3 government large hospitals", "1 private nursing home". */
export function facilityCountTitle(t: TopListsStrings, lang: Lang, n: number, own: string | null, type: { slug: string; name: string } | null): string {
  if (!own && !type) return (n === 1 ? t.facilities.countAllOne : t.facilities.countAllMany).replace("{n}", String(n));
  const nouns = type ? TYPE_NOUNS[type.slug]?.[lang] : null;
  const typeWord = type ? (nouns ? nouns[n === 1 ? 0 : 1] : tlData(lang, type.name).toLowerCase()) : lang === "hi" ? (n === 1 ? "सुविधा" : "सुविधाएं") : n === 1 ? "facility" : "facilities";
  const ownWord = own ? `${t.ownershipLower[own] ?? own} ` : "";
  return t.facilities.countType.replace("{n}", String(n)).replace("{own}", ownWord).replace("{type}", typeWord);
}
