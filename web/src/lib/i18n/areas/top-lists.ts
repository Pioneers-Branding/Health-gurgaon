const MONTHS_HI: Record<string, string> = {
  Jan: "जनवरी", Feb: "फ़रवरी", Mar: "मार्च", Apr: "अप्रैल", May: "मई", Jun: "जून",
  Jul: "जुलाई", Aug: "अगस्त", Sep: "सितंबर", Oct: "अक्टूबर", Nov: "नवंबर", Dec: "दिसंबर",
};

function onePart(text: string): string {
  const t = text.trim();
  if (DATA_HI[t]) return DATA_HI[t];
  let m = /^Sector (\w+)$/i.exec(t);
  if (m) return `सेक्टर ${m[1]}`;
  m = /^([\d,]+\+?) beds$/i.exec(t);
  if (m) return `${m[1]} बेड`;
  m = /^BASED ON ([\d,]+) VERIFIED REVIEWS$/i.exec(t);
  if (m) return `${m[1]} सत्यापित समीक्षाओं पर आधारित`;
  m = /^([\d,]+) reviews$/i.exec(t);
  if (m) return `${m[1]} समीक्षाएं`;
  m = /^([A-Z]{3}) (\d{4})$/.exec(t);
  if (m) {
    const k = m[1].charAt(0) + m[1].slice(1).toLowerCase();
    if (MONTHS_HI[k]) return `${MONTHS_HI[k]} ${m[2]}`;
  }
  // "Hindi, English, Telugu"
  if (/^[A-Za-z]+(, [A-Za-z]+)+$/.test(t) && t.split(", ").every((w) => DATA_HI[w])) return t.split(", ").map((w) => DATA_HI[w]).join(", ");
  // "Son of a patient, Sector 49"
  const comma = t.lastIndexOf(", ");
  if (comma > 0) {
    const head = t.slice(0, comma);
    const tail = t.slice(comma + 2);
    if (DATA_HI[head]) return `${DATA_HI[head]}, ${onePart(tail)}`;
  }
  return t;
}

/** Stored English data in the page language: whole strings first, then " · "-separated parts
 * ("Sector 38 · 24×7 emergency · 1,000+ beds"); unknown parts (names, places) stay as stored. */
export function tlData(lang: Lang, text: string): string {
  if (lang !== "hi" || !text) return text;
  if (DATA_HI[text]) return DATA_HI[text];
  return text
    .split(" · ")
    .map((part) => onePart(part))
    .join(" · ");
}

/** "Sep" → "सितंबर" in Hindi (month names in "▲ 1 since Sep"). */
export function monthName(lang: Lang, short: string): string {
  return lang === "hi" ? (MONTHS_HI[short] ?? short) : short;
}

